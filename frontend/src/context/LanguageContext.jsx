export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    return localStorage.getItem('kirana-lang') || 'en'
  })

  useEffect(() => {
    localStorage.setItem('kirana-lang', lang)
    document.documentElement.lang = lang
  }, [lang])

  const t = (key, variables = {}) => {
    const value = translations[lang]?.[key] || translations.en[key] || key
    return value
      .replace(/\\u([0-9a-f]{4})/gi, (_, code) => String.fromCharCode(parseInt(code, 16)))
      .replace(/\{(\w+)\}/g, (_, name) => variables[name] ?? '')
  }

  const toggleLang = () => setLang(prev => prev === 'en' ? 'ne' : 'en')

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, toggleLang }}>
      {children}
    </LanguageContext.Provider>
  )
}

// The hook intentionally lives next to its provider; fast refresh still works,
// it just falls back to a full reload for this file.
// eslint-disable-next-line react/only-export-components
export function useLanguage() {
  const ctx = useContext(LanguageContext)
  if (!ctx) throw new Error('useLanguage must be used within LanguageProvider')
  return ctx
}
